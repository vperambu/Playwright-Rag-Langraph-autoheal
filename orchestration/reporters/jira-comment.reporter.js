'use strict';

/**
 * JiraCommentReporter — builds a plain-text Jira comment summarising the run.
 * Can optionally publish via JiraClient when JIRA_PUBLISH_RESULTS=true.
 */

const jiraClient = require('../jira/jira.client');
const { logger } = require('../core/logger');
const log = logger.child('JiraCommentReporter');

class JiraCommentReporter {
  /**
   * Build the comment text (always) and publish if env says so.
   * @param {object} state
   * @returns {Promise<{ text: string, published: boolean, url: string|null }>}
   */
  async generate(state) {
    const { ticketId, testerResult, healerResult, reviewerResult, coverageReport, plannerResult, mode } = state;

    const tr = testerResult  || { summary: { total: 0, passed: 0, failed: 0 } };
    const hr = healerResult  || { status: 'no-failures', fixes: [] };
    const rv = reviewerResult || { score: 0, grade: 'N/A', findings: [], recommendations: [] };
    const cv = coverageReport || { coveragePercent: 0, totalRequirements: 0, coveredRequirements: 0 };
    const sc = plannerResult  ? plannerResult.scenarios.length : 0;

    const statusIcon  = tr.summary.failed === 0 ? '✅' : hr.fixes.length > 0 ? '🏥' : '⚠️';
    const gradeEmoji  = rv.grade === 'A' ? '🏆' : rv.grade === 'B' ? '👍' : rv.grade === 'C' ? '🟡' : '🔴';

    const healingSection = hr.status === 'healed' ? [
      '',
      '🏥 *Auto-Healing Applied*',
      `  Issues found: ${hr.healingSummary.issuesFound}`,
      `  Fixes applied: ${hr.healingSummary.fixesApplied}`,
      `  Success rate after healing: ${hr.healingSummary.successRate}`,
      ...hr.fixes.map(f => `  ✓ ${f.issue}: ${f.solution}`),
    ] : [];

    const text = [
      `🤖 *Automated Test Run Summary — ${ticketId}*`,
      '',
      `*Mode:* ${mode.toUpperCase()}  |  *Run at:* ${new Date().toISOString()}`,
      '',
      '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━',
      `${statusIcon} *Test Execution*`,
      `  Total spec files: ${tr.summary.total}`,
      `  Passed: ${tr.summary.passed}  |  Failed: ${tr.summary.failed}  |  Skipped: ${tr.summary.skipped || 0}`,
      ...healingSection,
      '',
      `📋 *Scenario Coverage*`,
      `  Scenarios generated: ${sc}`,
      `  Requirements covered: ${cv.coveredRequirements}/${cv.totalRequirements} (${cv.coveragePercent}%)`,
      cv.uncoveredRequirements && cv.uncoveredRequirements.length
        ? `  ⚠ Uncovered: ${cv.uncoveredRequirements.slice(0, 3).join('; ')}`
        : '  All requirements mapped ✓',
      '',
      `${gradeEmoji} *Code Quality*`,
      `  Score: ${rv.score}/100  (Grade: ${rv.grade})`,
      rv.findings.length
        ? `  Findings: ${rv.findings.slice(0, 3).map(f => f.message).join('; ')}`
        : '  No critical findings ✓',
      '',
      `💡 *Top Recommendations*`,
      ...(rv.recommendations.slice(0, 3).map(r => `  • ${r}`)),
      '',
      '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━',
      `_Generated by MultiAgent Orchestration System v1.0 (with Auto-Healing)_`
    ].join('\n');

    const shouldPublish = process.env.JIRA_PUBLISH_RESULTS === 'true' && mode !== 'mock';
    let published = false;
    let publishUrl = null;

    if (shouldPublish) {
      try {
        log.info('Publishing comment to Jira', { ticketId });
        const response = await jiraClient.addComment(ticketId, text);
        published  = true;
        publishUrl = response.self || null;
        log.info('Comment published', { ticketId, url: publishUrl });
      } catch (err) {
        log.error('Failed to publish Jira comment', { error: err.message });
      }
    } else {
      log.info('Jira publish skipped', {
        reason: shouldPublish ? 'mock mode' : 'JIRA_PUBLISH_RESULTS not set to true'
      });
    }

    return { text, published, url: publishUrl };
  }
}

module.exports = new JiraCommentReporter();
